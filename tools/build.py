def tl(rows):
    out = ['<ul class="tl">']
    for t, s, e, link, w, d in rows:
        a = '<a href="%s">%s</a>' % (link, w) if link else w
        out.append('<li data-start="%s" data-end="%s"><span class="t">%s</span><span class="w">%s%s</span></li>'
                   % (s, e, t, a, '<span>%s</span>' % d if d else ''))
    out.append('</ul>')
    return ''.join(out)


