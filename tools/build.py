STOPS = []


def stop(sid, num, cls, time, start, end, title, teaser, thumb, body, tag=''):
    STOPS.append(dict(id=sid, num=num, cls=cls, time=time, start=start, end=end, title=title, teaser=teaser,
                      thumb=thumb, body=body, tag=tag))


def render_stop(s):
    tag = '<span class="tag">%s</span>' % s['tag'] if s['tag'] else ''
    return ('<details class="stop" id="%s" data-start="%s" data-end="%s"><summary>'
            '<span class="num %s">%s</span>'
            '<span class="st"><span class="time">%s</span><b>%s%s</b><span class="teaser">%s</span></span>'
            '<img class="thumb" src="img/%s-t.webp" width="60" height="60" loading="lazy" alt="">'
            '</summary><div class="body">%s</div></details>'
            % (s['id'], s['start'], s['end'], s['cls'], s['num'], s['time'], s['title'], tag, s['teaser'], s['thumb'], s['body']))


def kv(*pairs):
    return '<dl class="kv">' + ''.join('<dt>%s</dt><dd>%s</dd>' % p for p in pairs) + '</dl>'


