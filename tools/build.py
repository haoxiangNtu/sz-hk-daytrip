def credit(key):
    c = CRED[key]
    return '<a href="%s" title="Wikimedia Commons 原图">%s · %s</a>' % (html.escape(c['page']), html.escape(c['artist']), c['lic'])


def fig(key, cap, alt=None, cls=''):
    c = CRED[key]
    return ('<figure%s><img src="img/%s.webp" width="%d" height="%d" loading="lazy" alt="%s">'
            '<figcaption>%s <span class="cr">%s</span></figcaption></figure>'
            % (' class="%s"' % cls if cls else '', key, c['w'], c['h'], html.escape(alt or cap), cap, credit(key)))


def mapfig(name, w, h, cap):
    return ('<figure><a href="img/%s.webp"><img src="img/%s.webp" width="%d" height="%d" loading="lazy" alt="%s"></a>'
            '<figcaption>%s 点图可放大。<span class="cr">底图 © OpenStreetMap contributors（ODbL），路线为示意。</span></figcaption></figure>'
            % (name, name, w, h, html.escape(cap), cap))


def more(title, body):
    return '<details class="more"><summary>%s</summary><div class="body">%s</div></details>' % (title, body)


def fold(title, body, cls=''):
    return '<details class="%s"><summary>%s</summary><div class="body">%s</div></details>' % (cls, title, body)


def page(fname, title, body, desc):
    nav = ''.join('<a href="%s"%s>%s</a>' % (f, ' class="on"' if f == fname else '', t) for f, t in NAV)
    doc = '''<!doctype html>
<html lang="zh-CN">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>%s · 深圳→香港周六一日游</title>
<meta name="description" content="%s">
<link rel="stylesheet" href="assets/style.css">
</head>
<body>
<header class="top"><div class="in"><a class="brand" href="index.html">深港一日游</a><nav>%s</nav></div></header>
<main class="wrap">
%s
<footer>
<p>整理于 %s。巴士班次来自环岛中港通 2026-11-11 版深圳线单张，出发前请在小程序里再核对。<a href="about.html">资料来源、图片署名、待确认事项</a></p>
</footer>
</main>
<script src="assets/app.js"></script>
</body>
</html>
''' % (title, desc, nav, body, UPDATED)
    open(os.path.join(ROOT, fname), 'w', encoding='utf-8').write(doc)
    print('wrote', fname, len(doc))


